const codesByLength = [...APP_ERROR_CODES]
  .filter((code) => code !== "UNKNOWN" && code !== "NETWORK")
  .sort((a, b) => b.length - a.length);

export function findKnownCodeInText(text: string): AppErrorCode | null {
  for (const code of codesByLength) {
    if (text.includes(code)) return code;
  }
  return null;
}
